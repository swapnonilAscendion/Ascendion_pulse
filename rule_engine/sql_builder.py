"""
Turns a validated RuleSpec into SQL. All names come from schema_config; all values are
escaped literals, and attributes/operators were allow-listed by rule_spec.validate().
"""
from __future__ import annotations

from . import schema_config as cfg
from .rule_spec import Condition, RuleSpec


def lit(v) -> str:
    """SQL literal for a Python value."""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, int):
        return str(v)
    return "N'" + str(v).replace("'", "''") + "'"


def _grade_number(expr: str) -> str:
    return f"TRY_CAST(SUBSTRING({expr}, {len(cfg.GRADE_PREFIX) + 1}, 10) AS INT)"


def condition_sql(c: Condition, alias: str = "e") -> str:
    key = cfg.condition_attributes()[c.attribute]
    col = f"{alias}.{cfg.C('employee', key)}"
    vals = c.values()
    if c.operator in cfg.LIST_OPERATORS:
        return f"{col} {c.operator} ({', '.join(lit(v) for v in vals)})"
    if key == "grade" and c.operator in {">", ">=", "<", "<="}:
        return f"{_grade_number(col)} {c.operator} {int(vals[0][len(cfg.GRADE_PREFIX):])}"
    op = "<>" if c.operator == "!=" else c.operator
    return f"{col} {op} {lit(vals[0])}"


def question_filter_sql(spec: RuleSpec, q: str = "q", t: str = "t") -> str:
    parts = []
    if spec.themes:
        parts.append(f"{t}.{cfg.C('theme', 'name')} IN ({', '.join(lit(x) for x in spec.themes)})")
    if spec.question_ids:
        parts.append(f"{q}.{cfg.C('question', 'id')} IN ({', '.join(str(int(i)) for i in spec.question_ids)})")
    where = [f"({' OR '.join(parts)})",
             f"{q}.{cfg.C('question', 'approval_status')} = N'Approved'",
             f"{q}.{cfg.C('question', 'is_active')} = 1"]
    return "\n  AND ".join(where)


def _questions_from(q: str = "q", t: str = "t") -> str:
    return (f"{cfg.T('question')} {q}\n"
            f"JOIN {cfg.T('theme')} {t} ON {t}.{cfg.C('theme', 'id')} = {q}.{cfg.C('question', 'theme_id')}")


def build_insert_sql(spec: RuleSpec, created_by: str | None = None) -> str:
    """One transaction: Rule -> RuleCondition rows -> RuleQuestion rows (sequenced)."""
    rule_values = {
        "name": spec.rule_name, "description": spec.description,
        "trigger_frequency": spec.trigger_frequency, "effective_from": spec.effective_from,
        "effective_to": spec.effective_to, "priority": spec.priority, "is_active": True,
        "status": "Draft", "source_text": spec.source_text, "created_by": created_by,
    }
    rule_values = {k: v for k, v in rule_values.items() if cfg.has("rule", k)}
    rule_cols = ", ".join(cfg.C("rule", k) for k in rule_values)
    rule_vals = ", ".join(lit(v) for v in rule_values.values())

    rc = "rule_condition"
    cond_rows = "\n".join(
        f"INSERT INTO {cfg.T(rc)} ({cfg.C(rc, 'rule_id')}, {cfg.C(rc, 'attribute')}, {cfg.C(rc, 'operator')}, {cfg.C(rc, 'value')})\n"
        f"VALUES (@RuleID, {lit(c.attribute)}, {lit(c.operator)}, {lit(c.value)});"
        for c in spec.conditions
    ) or "-- No conditions: rule applies to all active employees."

    rq = "rule_question"
    return f"""/* Rule: {spec.rule_name}
   From: {spec.source_text or '-'}
   Generated by rule_engine - review before running. */
SET XACT_ABORT ON;
BEGIN TRAN;

DECLARE @RuleID BIGINT;

INSERT INTO {cfg.T('rule')} ({rule_cols})
VALUES ({rule_vals});
SET @RuleID = SCOPE_IDENTITY();

{cond_rows}

INSERT INTO {cfg.T(rq)} ({cfg.C(rq, 'rule_id')}, {cfg.C(rq, 'question_id')}, {cfg.C(rq, 'sequence')}, {cfg.C(rq, 'is_active')})
SELECT @RuleID, q.{cfg.C('question', 'id')}, ROW_NUMBER() OVER (ORDER BY q.{cfg.C('question', 'id')}), 1
FROM {_questions_from()}
WHERE {question_filter_sql(spec)};

IF @@ROWCOUNT = 0
    THROW 50001, 'No approved, active questions matched this rule.', 1;

COMMIT;
SELECT @RuleID AS RuleID;
"""


def build_preview_sql(spec: RuleSpec, top: int = cfg.PREVIEW_TOP) -> str:
    """Read-only: who would get which questions, plus counts. Safe to run before saving."""
    e = "employee"
    where = [f"e.{cfg.C(e, 'is_active')} = 1"] + [condition_sql(c) for c in spec.conditions]
    emp_where = "\n  AND ".join(where)
    show = ["id", "name"] + [cfg.condition_attributes()[c.attribute] for c in spec.conditions]
    emp_cols = ", ".join(f"e.{cfg.C(e, k)}" for k in dict.fromkeys(show))

    return f"""/* Preview for: {spec.rule_name} (read-only) */
WITH Questions AS (
    SELECT q.{cfg.C('question', 'id')} AS QuestionID, q.{cfg.C('question', 'text')} AS QuestionText,
           t.{cfg.C('theme', 'name')} AS ThemeName,
           ROW_NUMBER() OVER (ORDER BY q.{cfg.C('question', 'id')}) AS SequenceNo
    FROM {_questions_from()}
    WHERE {question_filter_sql(spec)}
),
Employees AS (
    SELECT {emp_cols}
    FROM {cfg.T(e)} e
    WHERE {emp_where}
)
SELECT TOP ({int(top)}) emp.*, q.SequenceNo, q.ThemeName, q.QuestionID, q.QuestionText
FROM Employees emp CROSS JOIN Questions q
ORDER BY emp.{cfg.C(e, 'id')}, q.SequenceNo;

/* Counts shown to HR next to the preview */
WITH Questions AS (
    SELECT q.{cfg.C('question', 'id')} FROM {_questions_from()}
    WHERE {question_filter_sql(spec)}
)
SELECT (SELECT COUNT(*) FROM {cfg.T(e)} e WHERE {emp_where}) AS EmployeesMatched,
       (SELECT COUNT(*) FROM Questions) AS QuestionsMatched;
"""
