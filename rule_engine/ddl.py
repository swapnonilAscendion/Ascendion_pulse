"""Generates the CREATE TABLE script from schema_config. Never edit the generated .sql by hand."""
from __future__ import annotations

from . import schema_config as cfg


def _check_sql(table_key: str, template: str) -> str | None:
    """Fill {column_key} / {LIST_NAME} placeholders; None if it uses a column that is switched off."""
    names = {k: f"[{c.name}]" for k, c in cfg.columns(table_key).items()}
    names.update({k: cfg.sql_list(v) for k, v in cfg.VALUE_LISTS.items()})
    try:
        return template.format_map(names)
    except KeyError:
        return None


def table_ddl(table_key: str) -> str:
    t = cfg.TABLES[table_key]
    cols = cfg.columns(table_key)
    lines = []
    for c in cols.values():
        line = f"    [{c.name}] {c.type}"
        if c.identity:
            line += " IDENTITY(1,1)"
        line += " NULL" if c.nullable else " NOT NULL"
        if c.default is not None:
            line += f" CONSTRAINT [DF_{t.name}_{c.name}] DEFAULT ({c.default})"
        if c.proposed:
            line += " /* PROPOSED - not in glossary yet */"
        lines.append(line)

    pk = [c.name for c in cols.values() if c.pk]
    cons = [f"    CONSTRAINT [PK_{t.name}] PRIMARY KEY ({', '.join(f'[{n}]' for n in pk)})"]
    cons += [f"    CONSTRAINT [UQ_{t.name}_{c.name}] UNIQUE ([{c.name}])" for c in cols.values() if c.unique]
    for group in t.unique_together:
        if all(k in cols for k in group):
            col_names = [cols[k].name for k in group]
            cons.append(f"    CONSTRAINT [UQ_{t.name}_{'_'.join(col_names)}] UNIQUE ({', '.join(f'[{n}]' for n in col_names)})")
    for c in cols.values():
        if c.fk:
            ref_t, ref_c = c.fk
            # Glossary principle 7: no cascading deletes - default NO ACTION restricts deletion.
            cons.append(f"    CONSTRAINT [FK_{t.name}_{c.name}] FOREIGN KEY ([{c.name}]) "
                        f"REFERENCES {cfg.T(ref_t)} ({cfg.C(ref_t, ref_c)})")
    for i, template in enumerate(t.checks, 1):
        expr = _check_sql(table_key, template)
        if expr:
            cons.append(f"    CONSTRAINT [CK_{t.name}_{i}] CHECK ({expr})")

    body = ",\n".join(lines + cons)
    return (f"/* {t.name}: {t.desc} */\n"
            f"IF OBJECT_ID(N'{cfg.DB_SCHEMA}.{t.name}') IS NULL\n"
            f"CREATE TABLE {cfg.T(table_key)} (\n{body}\n);\nGO\n")


def schema_ddl() -> str:
    header = (
        "/* =====================================================================\n"
        "   Ascendion Pulse - schema (Glossary 2.xlsx, \"Final Version\")\n"
        "   GENERATED by `python main.py ddl` from rule_engine/schema_config.py.\n"
        "   Do not edit by hand - change schema_config.py and regenerate.\n"
        f"   Schema: {cfg.DB_SCHEMA}   Proposed columns included: {cfg.INCLUDE_PROPOSED}\n"
        "   Safe to re-run: tables are created only if they do not exist.\n"
        "   ===================================================================== */\n\n"
    )
    schema = (f"IF SCHEMA_ID(N'{cfg.DB_SCHEMA}') IS NULL EXEC(N'CREATE SCHEMA [{cfg.DB_SCHEMA}]');\nGO\n\n"
              if cfg.DB_SCHEMA != "dbo" else "")
    return header + schema + "\n".join(table_ddl(k) for k in cfg.TABLES)
